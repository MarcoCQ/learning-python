"""
2. Comparaciones completas
Crea un programa que pida dos números y muestre el resultado de las siguientes comparaciones:
- Igual (==)
- Diferente (!=)
- Mayor (>)
- Menor (<)
- Mayor o igual (>=)
- Menor o igual (<=)

"""
num1 = float(input("ingrese un número:"))
