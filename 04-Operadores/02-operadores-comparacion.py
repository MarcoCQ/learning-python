"""
    Operadores de comparacion

    (==): Sirve para validar que dos valores sean iguales
    (!=): Valida que los valores no sean iguales
    (>): Verifica que un valor sea mayor que el otro
    (<): Verifica que un valor sea menor que el otro
    (>=): Validar el un valor sea mayor o igual que el otro
    (<=): Validar el un valor sea menor o igual que el otro

"""

x = 20
y = 5

print("Igual:", x == y)
print("Diferente:", x != y)
print("Mayor:",x > y)
print("Menor:",x < y)
print("Mayor igual:",x >= y)
print("Menor igual:",x <= y)
